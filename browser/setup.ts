// Общая подготовка браузерных E2E: перед каждым тестом localStorage очищается — сохранённые наборы
// звука, мут и правки панели одного теста не влияют на другие.
import { beforeEach } from 'vitest';
import { config } from '@/config';

beforeEach(() => {
  localStorage.clear();

  // Режим сцены — тоже состояние между тестами: тест scene-mode переключает селект прямо в config,
  // и без сброса его падение оставило бы последующие тесты в замёрзшей демо-сцене.
  config.SCENE_MODE = 'game';
});
