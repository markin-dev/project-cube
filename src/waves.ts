// Список волн игры. Чтобы поменять или добавить волну, достаточно править этот файл.
//
// Первый проход по списку — обучающий круг: волны идут ровно как записаны, от трёх крошек до брута.
// Дальше составы повторяются по кругу (11-я волна — состав первой, 12-я — второй, …), а отсчёт волн
// продолжается: 11, 12, 13 … Сила растёт с каждой волной: у волны есть HP-бюджет (сколько здоровья во всех
// её врагах вместе), первая после круга — WAVE_ENDLESS_BUDGET, каждая следующая — в WAVE_GROWTH раз больше.
// Состав подгоняется под бюджет: врагов становится больше, а каждый — крепче и дороже по опыту
// (см. getWaveScale в src/schedule.ts и «РОСТ ВОЛН» в config.ts). Победы нет — игрок доходит так далеко,
// куда хватит сил.
//
// Волна состоит из групп. У каждой группы:
//   shape    — ГДЕ появятся враги: форма и её параметры (единственная форма random описана в src/patterns.ts);
//   delay    — КОГДА группа начнёт появляться: не позже стольких секунд от начала волны (по умолчанию 0).
//              Раньше — если все предыдущие группы уже появились целиком и все их враги убиты:
//              тогда следующая группа начинается сразу. Группы начинаются строго по порядку списка;
//   interval — пауза между врагами группы в секундах. 0 или не указан — все разом,
//              иначе по одному в порядке точек формы (у random точки в случайном порядке);
//   enemy    — КТО: тип врагов группы ('tiny', 'small', 'normal', 'big', 'brute' — см. ENEMY_KINDS
//              в config.ts). Не указан — у каждого врага группы случайный тип.
//
// Волна закончена, когда все её группы начались, все враги появились и убиты. Следующая начинается сразу,
// так что паузу перед волной делаем через delay у её первой группы (у первой группы delay — только
// задержка: предыдущих групп нет).
//
// В обучающем круге сложность растёт по трём направлениям: крепче типы врагов (tiny → small → normal →
// big → brute), больше их и плотнее темп; HP-бюджет растёт примерно в 1.25 раза за волну, от 30 до 240.
// Ориентир по балансу: стартовый куб стреляет два раза в секунду (FIRE_INTERVAL 0.5), одно попадание —
// в среднем ~17 HP (урон 10–20 и криты). Крошке (10 HP) хватает одного выстрела, обычному (40 HP) — трёх,
// то есть ~1.5 с, громиле (120 HP) — восьми, ~4 с. Враг идёт до куба 4–7 секунд. Без прокачки куб
// проходит круг на пределе и погибает в первых волнах после него.
// Точные числа — в ENEMY_KINDS, FIRE_INTERVAL и PROJECTILE_DAMAGE_MIN/MAX (config.ts).
//
// Чтобы проверить конкретную волну, выбери её в селекте «Волна» отладочной панели (?debug, см. debug.ts) —
// игра начнётся с неё сразу (и с поздней тоже: 20, 30, 40, 50).
//
// Ёмкость: random — форма-область, точки равномерны по площади кольца спавна, так что count можно
// крутить свободно: при тесноте подборщик места строит врагов вверх столбами (см. src/spawn-placement.ts),
// а не размазывает их по полу.
